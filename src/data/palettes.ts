// Helper to attach hex and symbol
function makePalette(brand: BrandKey, rawList: Array<{ code: string; name: string; hex: string }>): BeadColor[] {
  return rawList.map((item, idx) => ({
    id: `${brand}_${item.code}`,
    code: item.code,
    name: item.name,
    hex: item.hex,
    rgb: hexToRgb(item.hex),
    brand,
    symbol: item.code,
    enabled: true,
  }));
}

