export function hexToRgb(hex: string): [number, number, number] {
  const clean = hex.replace('#', '');
  const value = Number.parseInt(clean, 16);
  return [(value >> 16) & 255, (value >> 8) & 255, value & 255];
}

function makePalette(
  brand: BrandKey,
  rawColors: readonly RawColor[],
  isScreenReferenceOnly: (code: string) => boolean = () => false,
): BeadColor[] {
  return rawColors.map(({ code, name, hex }) => ({
    id: `${brand}_${code}`,
    code,
    name,
    hex,
    rgb: hexToRgb(hex),
    brand,
    symbol: code,
    enabled: true,
    ...(isScreenReferenceOnly(code) ? { screenReferenceOnly: true } : {}),
  }));
}

